"""
Markdown report generation.

This module is responsible for rendering report content as
Markdown and writing the resulting output to disk.

Functions in this module should focus solely on Markdown
generation and export functionality.
"""

# ---------------------------------------------------------------------------
# Markdown Export
# ---------------------------------------------------------------------------

def render_markdown(report):
    """
    Render a password audit report as Markdown.

    Report sections are assembled into a standard structure
    containing the executive summary, technical commentary,
    and remediation guidance.

    Args:
        report (dict):
            Report content generated by the reporting modules.

    Returns:
        str:
            Complete Markdown report.
    """

    lines = []

    lines.append("# Executive Summary")
    lines.append("")
    lines.append(report["executive_summary"])
    lines.append("")

    summary = report.get("summary", {})
    if summary:
        lines.append("# Audit Summary")
        lines.append("")
        for label, key, suffix in (
            ("Total passwords recovered", "total_passwords", ""),
            ("Enabled users", "enabled_users", ""),
            ("Unique passwords", "unique_passwords", ""),
            ("Crack rate", "crack_rate", "%"),
            ("Accounts with LM hashes", "lm_hashes", ""),
            ("LM passwords recovered", "lm_passwords_recovered", ""),
            ("LM recovery rate", "lm_recovery_rate", "%"),
        ):
            if key in summary:
                lines.append(f"- **{label}:** {summary[key]}{suffix}")
        lines.append("")

    lines.append("# Technical Commentary")
    lines.append("")
    lines.append(report["technical_commentary"])
    lines.append("")

    lines.append("# Remediation Guidance")
    lines.append("")
    lines.append(report["remediation_guidance"])
    lines.append("")

    lines.append("### References")
    lines.append("")
    lines.append(report["references"])
    lines.append("")

    findings = report.get("findings", [])
    if findings:
        lines.append("# Findings")
        lines.append("")

        for finding in findings:
            severity = finding.get("severity", "info").upper()
            category = finding.get("category", "general")
            lines.append(
                f"## [{severity}] {finding['id']} - {finding['title']}"
            )
            lines.append("")
            lines.append(f"**Category:** {category}")
            lines.append("")
            lines.append(finding.get("description", ""))
            lines.append("")
            remediation = finding.get("remediation")
            if remediation:
                lines.append(f"**Remediation:** {remediation}")
                lines.append("")

    return "\n".join(lines)


def write_markdown(path, content):
    """
    Write a Markdown report to disk.

    Args:
        path (str):
            Output file path.

        content (str):
            Markdown content to write.

    Returns:
        None
    """

    with open(path, "w", encoding="utf-8") as f:
        f.write(content)