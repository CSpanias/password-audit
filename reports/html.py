"""Self-contained HTML report and interactive findings dashboard."""

import json


def _safe_json(report):
    return (
        json.dumps(report, ensure_ascii=False)
        .replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def render_html(report):
    """Render a self-contained dashboard with no external assets."""
    data = _safe_json(report)
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Password Audit Report</title>
  <style>
    :root {{ color-scheme: light; font-family: system-ui, sans-serif; color: #172033; background: #f3f6fa; }}
    body {{ margin: 0; }}
    header {{ padding: 2rem max(1rem, calc((100% - 1100px) / 2)); background: #10233f; color: white; }}
    header h1 {{ margin: 0; }}
    main {{ max-width: 1100px; margin: 2rem auto; padding: 0 1rem; }}
    .cards {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(min(100%, 190px), 1fr)); gap: 1rem; margin-bottom: 2rem; }}
    .card, .finding, .narrative details {{ background: white; border: 1px solid #dce3ed; border-radius: .6rem; }}
    .card {{ padding: 1rem; white-space: nowrap; overflow-x: auto; }}
    .card strong {{ display: block; font-size: 1.6rem; margin-top: .35rem; }}
    .card strong.recovery {{ font-size: 1.15rem; }}
    .card .unit {{ display: block; color: #53647b; font-size: .9rem; }}
    .filters {{ display: flex; flex-wrap: wrap; gap: .75rem; margin: 1rem 0; }}
    input, select {{ padding: .6rem; border: 1px solid #9aa8bb; border-radius: .35rem; background: white; color: inherit; }}
    input {{ flex: 1; min-width: 220px; }}
    #finding-count {{ color: #53647b; }}
    .finding {{ margin: .75rem 0; padding: 1rem; border-left: 5px solid #607d9d; }}
    .finding.critical, .finding.high {{ border-left-color: #b42318; }}
    .finding.medium {{ border-left-color: #b7791f; }}
    .finding.low {{ border-left-color: #2563a6; }}
    .finding h3 {{ margin: 0; }}
    .badge {{ display: inline-block; margin: .5rem .4rem .5rem 0; padding: .15rem .5rem; border-radius: 1rem; background: #e8edf4; font-size: .82rem; }}
    .narrative details {{ margin: .75rem 0; padding: 1rem; }}
    .narrative summary {{ cursor: pointer; font-weight: 650; }}
    .narrative .text {{ white-space: pre-line; line-height: 1.55; }}
    .narrative h3 {{ margin: 1.25rem 0 .4rem; }}
    .copy-controls {{ display: flex; align-items: center; gap: .75rem; margin: .75rem 0; }}
    .copy-button {{ padding: .45rem .7rem; border: 1px solid #9aa8bb; border-radius: .35rem; background: #f3f6fa; color: inherit; cursor: pointer; }}
    .copy-button:disabled {{ cursor: wait; opacity: .7; }}
    .copy-status {{ color: #53647b; font-size: .9rem; }}
    .copy-buffer {{ position: fixed; left: -9999px; top: 0; }}
    .reference-list {{ padding-left: 1.25rem; overflow-wrap: anywhere; }}
    .reference-list li {{ margin: .35rem 0; }}
    .empty {{ padding: 1rem; color: #53647b; }}
    footer {{ color: #53647b; margin: 2rem 0; font-size: .9rem; }}
  </style>
</head>
<body>
  <header><h1>Password Audit Report</h1><p>Interactive, local-only findings summary</p></header>
  <main>
    <section class="cards" id="audit-summary" aria-label="Audit summary">
      <div class="card" role="group" aria-label="Recovered NTLM passwords / enabled users" title="Recovered NTLM passwords / enabled users">Recovered NTLM<strong class="recovery" id="ntlm-recovery">-</strong></div>
      <div class="card" role="group" aria-label="Fully recovered LM passwords / accounts with LM hashes" title="Fully recovered LM passwords / accounts with LM hashes">Recovered LM<strong class="recovery" id="lm-recovery">-</strong></div>
      <div class="card" role="group" aria-label="Unique recovered NTLM passwords" title="Unique recovered NTLM passwords">Unique NTLM<strong id="unique-passwords">-</strong></div>
    </section>
    <section class="narrative" id="narrative" aria-label="Report narrative"></section>
    <section aria-labelledby="findings-heading">
      <h2 id="findings-heading">Findings</h2>
      <div class="filters">
        <input id="search" type="search" placeholder="Search findings" aria-label="Search findings">
        <select id="severity-filter" aria-label="Filter by severity"><option value="">All severities</option></select>
        <select id="category-filter" aria-label="Filter by category"><option value="">All categories</option></select>
      </div>
      <p id="finding-count" aria-live="polite"></p>
      <div id="findings"></div>
    </section>
    <footer>Generated by Password Audit. This file works offline and does not load external resources.</footer>
  </main>
  <script id="report-data" type="application/json">{data}</script>
  <script>
    const report = JSON.parse(document.getElementById("report-data").textContent);
    const summary = report.summary || {{}};
    const findings = report.findings || [];
    const number = value => new Intl.NumberFormat().format(Number(value) || 0);

    const recovery = (count, total, rate) =>
      `${{number(count)}}/${{number(total)}} (${{total ? `${{rate}}%` : "N/A"}})`;
    document.getElementById("ntlm-recovery").textContent =
      recovery(summary.total_passwords, summary.enabled_users, summary.crack_rate);
    document.getElementById("lm-recovery").textContent =
      recovery(summary.lm_passwords_recovered, summary.lm_hashes, summary.lm_recovery_rate);
    document.getElementById("unique-passwords").textContent = number(summary.unique_passwords);

    const findingSummary = report.finding_summary || [];
    const units = {{
      "accounts": "accounts",
      "recovered passwords": "recovered",
      "unique passwords": "unique",
      "account pairs": "pairs",
      "shared credential groups": "groups"
    }};
    const cards = document.getElementById("audit-summary");
    for (const item of findingSummary) {{
      const card = document.createElement("div");
      card.className = "card";
      card.setAttribute("role", "group");
      const description = `${{item.title}} (${{item.unit}}): ${{number(item.count)}}`;
      card.setAttribute("aria-label", description);
      card.title = description;
      const title = document.createElement("span");
      title.textContent = item.label;
      const count = document.createElement("strong");
      count.textContent = number(item.count);
      const unit = document.createElement("span");
      unit.className = "unit";
      unit.textContent = units[item.unit] || item.unit;
      card.append(title, count, unit);
      cards.append(card);
    }}

    const narrative = document.getElementById("narrative");
    const narrativeSections = [
      ["executive_summary", "Executive Summary"],
      ["technical_commentary", "Technical Commentary"],
      ["remediation_guidance", "Remediation Guidance"]
    ];

    async function copyMarkdown(text) {{
      if (navigator.clipboard?.writeText && window.isSecureContext) {{
        await navigator.clipboard.writeText(text);
        return;
      }}

      const buffer = document.createElement("textarea");
      buffer.value = text;
      buffer.className = "copy-buffer";
      document.body.append(buffer);
      buffer.select();
      let copied;
      try {{
        copied = document.execCommand("copy");
      }} finally {{
        buffer.remove();
      }}
      if (!copied) throw new Error("Clipboard access is unavailable.");
    }}

    function renderReferenceList(references) {{
      const list = document.createElement("ul");
      list.className = "reference-list";
      for (const line of String(references).split(/\\r?\\n/)) {{
        const entry = document.createElement("li");
        const match = line.match(/^- \\[([^\\]]+)\\]\\((https?:\\/\\/.+)\\)$/);
        if (match) {{
          const link = document.createElement("a");
          link.href = match[2];
          link.textContent = match[1];
          link.target = "_blank";
          link.rel = "noopener noreferrer";
          entry.append(link);
        }} else {{
          entry.textContent = line;
        }}
        list.append(entry);
      }}
      return list;
    }}

    function createCopyControls(label, markdown) {{
      const controls = document.createElement("div");
      controls.className = "copy-controls";
      const copyButton = document.createElement("button");
      copyButton.className = "copy-button";
      copyButton.type = "button";
      copyButton.textContent = label;
      const copyStatus = document.createElement("span");
      copyStatus.className = "copy-status";
      copyStatus.setAttribute("aria-live", "polite");
      copyButton.addEventListener("click", async () => {{
        copyButton.disabled = true;
        copyStatus.textContent = "Copying...";
        try {{
          await copyMarkdown(markdown);
          copyStatus.textContent = "Copied Markdown to clipboard.";
        }} catch {{
          copyStatus.textContent = "Copy failed. Select and copy the text manually.";
        }} finally {{
          copyButton.disabled = false;
        }}
      }});
      controls.append(copyButton, copyStatus);
      return controls;
    }}

    const allMarkdown = [];
    for (const [key, title] of narrativeSections) {{
      const sectionText = report[key];
      const references = key === "remediation_guidance" ? report.references : "";
      if (!sectionText && !references) continue;

      const markdown = [];
      if (sectionText) markdown.push(String(sectionText));
      if (references) markdown.push(`### References\\n\\n${{references}}`);
      const sectionMarkdown = markdown.join("\\n\\n");
      allMarkdown.push(`# ${{title}}\\n\\n${{sectionMarkdown}}`);

      const section = document.createElement("details");
      const heading = document.createElement("summary");
      heading.textContent = title;

      const text = document.createElement("p");
      text.className = "text";
      text.textContent = sectionText || "";
      section.append(heading, createCopyControls("Copy Markdown", sectionMarkdown), text);

      if (references) {{
        const referenceHeading = document.createElement("h3");
        referenceHeading.textContent = "References";
        section.append(referenceHeading, renderReferenceList(references));
      }}
      narrative.append(section);
    }}
    if (allMarkdown.length) {{
      narrative.prepend(createCopyControls("Copy All Markdown", allMarkdown.join("\\n\\n")));
    }}

    function addOptions(id, values) {{
      const select = document.getElementById(id);
      for (const value of values) {{
        const option = document.createElement("option");
        option.value = value;
        option.textContent = value.replaceAll("_", " ");
        select.append(option);
      }}
    }}

    addOptions("severity-filter", [...new Set(findings.map(f => f.severity || "info"))].sort());
    addOptions("category-filter", [...new Set(findings.map(f => f.category || "general"))].sort());

    const list = document.getElementById("findings");
    const emptyMessage = document.createElement("p");
    emptyMessage.className = "empty";
    list.append(emptyMessage);

    for (const finding of findings) {{
      const card = document.createElement("article");
      const severity = String(finding.severity || "info").toLowerCase();
      card.className = `finding ${{severity}}`;
      card.dataset.severity = severity;
      card.dataset.category = finding.category || "general";

      const title = document.createElement("h3");
      title.textContent = `${{finding.id}} - ${{finding.title}}`;
      const badges = document.createElement("div");
      for (const value of [severity, finding.category || "general"]) {{
        const badge = document.createElement("span");
        badge.className = "badge";
        badge.textContent = value.replaceAll("_", " ");
        badges.append(badge);
      }}
      card.append(title, badges);

      for (const [label, value] of [
        ["Description", finding.description],
        ["Remediation", finding.remediation]
      ]) {{
        if (!value) continue;
        const detail = document.createElement("details");
        const heading = document.createElement("summary");
        heading.textContent = label;
        const text = document.createElement("p");
        text.className = "text";
        text.textContent = value;
        detail.append(heading, text);
        card.append(detail);
      }}

      const evidence = finding.evidence || [];
      if (evidence.length) {{
        const detail = document.createElement("details");
        const heading = document.createElement("summary");
        heading.textContent = `Evidence (${{evidence.length}})`;
        const list = document.createElement("ul");
        for (const item of evidence) {{
          const entry = document.createElement("li");
          entry.textContent = item;
          list.append(entry);
        }}
        detail.append(heading, list);
        card.append(detail);
      }}
      const references = finding.references || [];
      if (references.length) {{
        const detail = document.createElement("details");
        const heading = document.createElement("summary");
        heading.textContent = "References";
        const markdown = references.map(url => `- [${{url}}](${{url}})`).join("\\n");
        detail.append(heading, renderReferenceList(markdown));
        card.append(detail);
      }}
      list.append(card);
    }}

    function updateFindings() {{
      const query = document.getElementById("search").value.trim().toLowerCase();
      const severity = document.getElementById("severity-filter").value;
      const category = document.getElementById("category-filter").value;
      let visible = 0;
      for (const card of list.querySelectorAll(".finding")) {{
        const match = (!severity || card.dataset.severity === severity)
          && (!category || card.dataset.category === category)
          && (!query || card.textContent.toLowerCase().includes(query));
        card.hidden = !match;
        if (match) visible++;
      }}
      document.getElementById("finding-count").textContent =
        `${{visible}} of ${{findings.length}} findings`;
      emptyMessage.hidden = visible > 0;
      emptyMessage.textContent = findings.length
        ? "No findings match the selected filters."
        : "No findings were generated.";
    }}

    for (const id of ["search", "severity-filter", "category-filter"]) {{
      document.getElementById(id).addEventListener("input", updateFindings);
      document.getElementById(id).addEventListener("change", updateFindings);
    }}
    updateFindings();
  </script>
</body>
</html>
"""
