"""
Remediation guidance generation.

This module converts analysis results into prioritised remediation
recommendations suitable for inclusion within password audit
reports.

Functions in this module should focus on producing remediation
guidance based on identified findings. Analysis logic should
remain within the analysis module.
"""

def remediation_guidance(results):
    """
    Generate remediation guidance based on password audit findings.

    Recommendations are included conditionally based on the
    weaknesses identified during analysis. This ensures that the
    guidance remains relevant to the assessed environment and
    avoids presenting unnecessary recommendations where no
    supporting evidence exists.

    Recommendations may be generated for:

    - Privileged account security
    - Password policy compliance
    - Password reuse
    - Predictable password construction
    - Multi-factor authentication

    Args:
        results (dict):
            Analysis results generated by the password analysis
        engine.

    Returns:
        str:
            Remediation guidance formatted as Markdown-ready text.
    """

    lines = []

    # ------------------------
    # Introduction
    # ------------------------

    lines.append(
        "Remediation efforts should be prioritised according to business "
        "risk and aligned with the organisation's wider identity "
        "and access management strategy:\n"
    )

    # ------------------------
    # Privileged Accounts
    # ------------------------

    if results["admins"]["count"] or results["privileged_users"]["count"]:
        affected = {
            account["username"].casefold()
            for key in ("admins", "privileged_users") for account in results[key]["accounts"]
        }
        lines.append(
            ("- The affected privileged account should have its password reset immediately "
             "and be reviewed to ensure it is protected by a strong, unique credential. "
             if len(affected) == 1 else
             "- The affected privileged accounts should have their passwords reset immediately "
             "and be reviewed to ensure they are protected by strong, unique credentials. ")
            + "Consider applying enhanced controls "
            "to privileged identities, including dedicated password policies, "
            "privileged access management solutions, and multi-factor "
            "authentication."
        )

    # ------------------------
    # LM-related findings
    # ------------------------

    if results["lm_hashes"]["count"]:

        recommendation = (
            "- LAN Manager (LM) hash storage should be disabled and "
            + ("the affected user should be required to change their password to remove the stored LM hash. "
               if results["lm_hashes"]["count"] == 1 else
               "affected users should be required to change their passwords to remove the stored LM hashes. ")
            + "Any legacy "
            "systems requiring LM compatibility should be identified and remediated where possible."
        )

        if results["lm_passwords"]["count"]:
        
            recommendation += (
                " The account for which a password was recovered from an LM hash should be required "
                "to change its password immediately in order to invalidate the recovered credential."
                if results["lm_passwords"]["count"] == 1 else
                " Accounts for which passwords were recovered from LM hashes should be required to "
                "change their passwords immediately in order to invalidate recovered credentials."
            )
    
            # Domain Admins with LM hashes
            if results["lm_admins"]["count"]:
    
                recommendation += (
                    (" The privileged account should be prioritised for immediate password reset and "
                     if results["lm_admins"]["count"] == 1 else
                     " Privileged accounts should be prioritised for immediate password reset and ")
                    + "reviewed for evidence of credential exposure or misuse."
                )

        lines.append(recommendation)

    # -------------------------------
    # Password Length Compliance
    # -------------------------------

    if results.get("hibp", {}).get("count"):
        lines.append(
            "- Reset passwords found in known breach data, prioritising "
            "privileged accounts, and screen new passwords against a "
            "regularly updated compromised-password blocklist."
        )

    if results["password_length"]["count"]:
        lines.append(
            "- Review the effective policies for accounts with passwords below the domain "
            "minimum, including fine-grained policies and earlier policy changes, and "
            "require password changes where appropriate. Longer passwords and passphrases "
            "generally provide greater resistance to offline password-cracking attacks "
            "and should be encouraged wherever possible."
        )

    # ---------------
    # Password Reuse
    # ---------------

    if (
        results["password_reuse_general"]["sharedPasswords"]
        or results["ntlm_hash_reuse"]["groups"]
    ):

        lines.append(
            "- Users should be encouraged to maintain unique passwords for all "
            "accounts and services. Where appropriate, password managers should "
            "be implemented to support the adoption of unique credentials and reduce "
            "reliance on reused passwords."
        )

    # ------------------------
    # Similarly-named reuse
    # ------------------------

    if results["similar_account_reuse"]["count"]:

        lines.append(
            "- Review similarly named accounts sharing credentials and require "
            "unique passwords. Prioritise accounts with different privilege "
            "levels to preserve account separation."
        )

    if any(
        any(account["groups"] for account in group["accounts"])
        for group in results["ntlm_hash_reuse"]["groups"]
    ):
        lines.append(
            "- Prioritise shared credentials involving selected privileged "
            "accounts, and replace them with unique passwords for each account."
        )

    # -------------------------------
    # Password Construction Practices
    # -------------------------------

    patterns = []

    if results["username_passwords"]["count"]:
        patterns.append("username-derived content")

    if results["company_words"]["count"]:
        patterns.append("organisation-related terminology")

    if results["common_passwords"]["count"]:
        patterns.append("commonly used password terms")

    if results["date_passwords"]["count"]:
        patterns.append("date-related references")

    if results["keyboard_walks"]["count"]:
        patterns.append("keyboard sequences")

    if patterns:
        lines.append(
            "- Users should select passwords that are unrelated "
            "to personal information, organisational terminology, "
            "or other predictable patterns. Technical controls such "
            "as password filtering solutions should also be considered "
            "to prevent the use of weak and commonly observed password "
            "constructions."
        )

    # ----------------------------
    # Multi-Factor Authentication
    # ----------------------------

    lines.append(
        "- Multi-factor authentication (MFA) should be enforced for "
        "all externally accessible services and privileged accounts "
        "wherever technically feasible. Whilst strong passwords remain "
        "important, MFA provides additional protection against password-"
        "based attacks and reduces the likelihood of account compromise "
        "following credential exposure."
    )

    return "\n".join(lines)


def remediation_references(results):
    """
        Generate remediation reference links based on
        identified findings.
    
        Returns:
            str: Markdown-formatted references section.
        """

    references = set()

    # Always include
    references.add("https://www.ncsc.gov.uk/collection/passwords")
    references.add("https://www.ncsc.gov.uk/guidance/multi-factor-authentication-online-services")
    references.add("https://pages.nist.gov/800-63-4/sp800-63b.html#appA")

    if results["password_length"]["count"]:
        references.add("https://pages.nist.gov/800-63-4/sp800-63b.html#length")

    if results["character_classes"]:
        references.add("https://pages.nist.gov/800-63-4/sp800-63b.html#complexity")

    if results.get("hibp", {}).get("count"):
        references.add("https://haveibeenpwned.com/Passwords")

    # Privileged accounts
    if results["admins"]["count"] or results["privileged_users"]["count"]:
        references.add(
            "https://learn.microsoft.com/security/privileged-access-workstations/privileged-access-access-model"
        )
        references.add(
            "https://learn.microsoft.com/en-us/microsoft-365/admin/misc/password-policy-recommendations?view=o365-worldwide#password-guidelines-for-administrators"
        )
        references.add(
            "https://learn.microsoft.com/en-us/previous-versions/windows/it-pro/windows-server-2008-R2-and-2008/cc770394(v=ws.10)"
        )

    # Presence of LM hashes
    if results["lm_hashes"]["count"]:
        references.add(
            "https://learn.microsoft.com/windows/security/threat-protection/security-policy-settings/network-security-do-not-store-lan-manager-hash-value-on-next-password-change"
        )

    # Password reuse
    if (
        results["password_reuse_general"]["sharedPasswords"]
        or results["similar_account_reuse"]["count"]
        or results["ntlm_hash_reuse"]["groups"]
    ):
        references.add(
            "https://specopssoft.com/blog/password-reuse-hidden-danger/"
        )

    # Predictable patterns
    if (
        results["username_passwords"]["count"]
        or results["company_words"]["count"]
        or results["common_passwords"]["count"]
        or results["date_passwords"]["count"]
        or results["keyboard_walks"]["count"]
    ):
        references.add(
            "https://www.ncsc.gov.uk/blog-post/the-logic-behind-three-random-words"
        )

    return "\n".join(f"- [{url}]({url})" for url in sorted(references))